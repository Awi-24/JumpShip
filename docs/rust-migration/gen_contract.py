"""
Regenerate the machine-readable API/DB contract used by the Rust port:

    docs/rust-migration/openapi.json   <- backend.main.app.openapi()
    docs/rust-migration/schema.sql     <- SQLAlchemy metadata rendered with the sqlite dialect

Run from the repo root:
    PYTHONPATH=. .venv/Scripts/python.exe docs/rust-migration/gen_contract.py   (Windows)
    PYTHONPATH=. .venv/bin/python docs/rust-migration/gen_contract.py           (Linux/macOS)

Importing backend.main runs init_db() and _migrate_db() at import time, so DATABASE_URL is
pointed at a throwaway SQLite file first - the real jobspy_ui.db is never touched.
"""
from __future__ import annotations

import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

OUT = Path(__file__).resolve().parent
ROOT = OUT.parents[1]
sys.path.insert(0, str(ROOT))

_tmp = tempfile.mkdtemp(prefix="jumpship-contract-")
os.environ["DATABASE_URL"] = f"sqlite:///{_tmp}/contract.db".replace("\\", "/")
os.environ.setdefault("DEBUG", "true")  # allow the default SECRET_KEY at import

SCHEMA_HEADER = """\
-- JumpShip SQLite schema, generated by docs/rust-migration/gen_contract.py from
-- backend/models/db_models.py (SQLAlchemy metadata, sqlite dialect). Do not edit by hand.
--
-- Conventions the Rust port must reproduce:
--   * Primary keys are TEXT uuid4 strings generated app-side (gen_uuid), except
--     user_profiles which /api/profile addresses as the fixed id 'singleton'.
--   * DateTime columns are stored by SQLAlchemy as 'YYYY-MM-DD HH:MM:SS[.ffffff]' text; server defaults use
--     CURRENT_TIMESTAMP (UTC, 'YYYY-MM-DD HH:MM:SS'). The API returns them via .isoformat() (no 'Z').
--     applications.applied_at is written with datetime.utcnow().
--   * JSON columns are TEXT holding JSON (SQLAlchemy JSON type on sqlite).
--   * onupdate=func.now() (updated_at) is applied by SQLAlchemy on UPDATE; there is no DB trigger.
--
-- Tables used by endpoints the frontend actually calls (see API.md):
--   applications        /api/applications*, /api/resume/generate-for-application, /api/interview/*
--   interview_sessions  /api/interview/*
--   user_profiles       /api/profile, /api/settings/llm-keys, tailored-resume contact context
--   generated_resumes   /api/resume/generate-for-application (insert only; list/download are unused)
-- Tables only touched by legacy/unused endpoints (can be dropped from a fresh port):
--   saved_jobs (/api/jobs/save*), resumes (/api/resume/upload), analyses (/api/analysis*),
--   settings (/api/settings/ai-keys, /platforms, /profile - legacy key/value store)
"""

SCHEMA_FOOTER = """\

-- ---------------------------------------------------------------------------
-- Runtime migrations: backend/main.py::_migrate_db() runs these ALTERs on every
-- startup, each in its own try/except (a failure such as "duplicate column name"
-- is logged at DEBUG and ignored). They exist for databases created before the
-- columns were added to the models; on a fresh database every column below is
-- already created by the CREATE TABLE statements above, so they are no-ops.
--
--   ALTER TABLE analyses ADD COLUMN keywords_matched JSON;
--   ALTER TABLE analyses ADD COLUMN keywords_missing JSON;
--   ALTER TABLE applications ADD COLUMN is_easy_apply BOOLEAN DEFAULT 0;
--   ALTER TABLE applications ADD COLUMN assessment_data JSON;
--   ALTER TABLE applications ADD COLUMN match_score INTEGER;
--   ALTER TABLE applications ADD COLUMN job_description TEXT;
--   ALTER TABLE user_profiles ADD COLUMN llm_keys_encrypted TEXT;
--
-- A port that must open databases written by older Python builds needs the same
-- idempotent "add column if missing" step for applications.* and user_profiles.llm_keys_encrypted
-- (analyses.* only matters if the legacy analyses table is kept).
-- There is no schema_version table; create_all() only creates missing tables and never alters.
"""


def main() -> None:
    from sqlalchemy.dialects import sqlite
    from sqlalchemy.schema import CreateIndex, CreateTable

    from backend.database import Base
    from backend.main import app
    import backend.models.db_models  # noqa: F401  (registers tables)

    # Starlette dispatches to the first matching route, so a later route with the same
    # (method, path) is dead code. Drop those before dumping, otherwise the OpenAPI path
    # item shows the shadowed handler (today: legacy POST /api/jobs/search shadowed by v2).
    seen: set[tuple[str, str]] = set()
    for route in list(app.router.routes):
        keys = {(m, route.path) for m in getattr(route, "methods", None) or ()}
        if keys and keys <= seen:
            print(f"shadowed (not dumped): {sorted(keys)} -> {route.endpoint.__module__}.{route.endpoint.__name__}")
            app.router.routes.remove(route)
        seen |= keys

    spec = app.openapi()
    (OUT / "openapi.json").write_text(
        json.dumps(spec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )

    dialect = sqlite.dialect()
    parts = [SCHEMA_HEADER]
    for table in Base.metadata.sorted_tables:
        ddl = "\n".join(line.rstrip() for line in str(CreateTable(table).compile(dialect=dialect)).strip().splitlines())
        parts.append(f"\n{ddl};\n")
        # Python-side defaults live in the ORM, not in the DDL: the port must apply them on insert.
        defaults = []
        for col in table.columns:
            if col.default is not None:
                arg = col.default.arg
                shown = getattr(arg, "__name__", None) if callable(arg) else repr(arg)
                defaults.append(f"{col.name}={shown}")
            if col.onupdate is not None:
                defaults.append(f"{col.name}=<now() on every UPDATE>")
        if defaults:
            parts.append("-- ORM (Python-side) defaults not in the DDL: " + ", ".join(defaults) + "\n")
        for index in sorted(table.indexes, key=lambda i: i.name or ""):
            parts.append(f"{str(CreateIndex(index).compile(dialect=dialect)).strip()};\n")
    parts.append(SCHEMA_FOOTER)
    (OUT / "schema.sql").write_text("".join(parts), encoding="utf-8", newline="\n")

    print(f"wrote {OUT / 'openapi.json'} ({len(spec['paths'])} paths)")
    print(f"wrote {OUT / 'schema.sql'} ({len(Base.metadata.sorted_tables)} tables)")


if __name__ == "__main__":
    try:
        main()
    finally:
        from backend.database import engine

        engine.dispose()
        shutil.rmtree(_tmp, ignore_errors=True)
